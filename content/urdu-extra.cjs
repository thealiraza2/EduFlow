module.exports = function urduExtra(units, poemUnits, offset = 0) {
  return units.map((u, i) => {
    const t = u.titleUr;
    const isPoem = poemUnits.includes(u.unit);
    const has = { M: 0, S: 0, L: 0 };
    u.q.forEach((q) => has[q[0]]++);
    const q = [];
    for (let k = 0; has.M + k < 8; k++) {
      const m = MCQ[(offset + i * 5 + k) % MCQ.length];
      q.push(["M", `${u.unit}.2`, null, m[0], m[1], m[2]]);
    }
    const shorts = isPoem ? SHORT_POEM : SHORT_PROSE;
    for (let k = 0; has.S + k < 5 && k < shorts.length; k++) q.push(["S", `${u.unit}.1`, null, shorts[k](t)]);
    if (has.S + shorts.length < 5) q.push(["S", `${u.unit}.2`, null, `"${t}" سے پانچ مشکل الفاظ چن کر ان کے معنی لکھیں اور جملوں میں استعمال کریں۔`]);
    const longs = [
      isPoem ? `"${t}" کے کسی دو اشعار کی تشریح کریں اور شاعر کا نام لکھیں۔` : `"${t}" کا تفصیلی خلاصہ لکھیں اور مصنف کا اندازِ بیان واضح کریں۔`,
      LONG_THEME[(offset + i) % LONG_THEME.length],
    ];
    for (let k = 0; has.L + k < 2; k++) q.push(["L", `${u.unit}.${k === 0 ? 1 : 2}`, null, longs[k], 10]);
    return { unit: u.unit, q };
  });
};
